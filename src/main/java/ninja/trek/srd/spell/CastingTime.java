package ninja.trek.srd.spell;

/**
 * Represents the casting time of a spell.
 */
public enum CastingTime {
    ACTION,         // 1 action
    BONUS_ACTION,   // 1 bonus action
    REACTION,       // 1 reaction
    MINUTE_1,       // 1 minute
    MINUTE_10,      // 10 minutes
    HOUR_1,         // 1 hour
    HOUR_8,         // 8 hours
    HOUR_24         // 24 hours
}
